--// ═══ STATE ═══════════════════════════════════════════════════════════════
local RNG = Random.new()
local State = {
	running = false,
	hops    = 0,
	status  = "idle",
	info    = "ready",
}

local function jitter(min, max)
	return RNG:NextNumber(min, max)
end

local function sleep(sec)
	local t = 0
	while t < sec do
		if not State.running then break end
		local step = math.min(0.25, sec - t)
		task.wait(step)
		t = t + step
	end
end

